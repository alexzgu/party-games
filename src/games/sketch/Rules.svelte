<p>Everyone joins the host's room on their <b>own phone</b>. The host picks the mode in Settings.</p>
<h4>Telephone</h4>
<ol>
  <li>Everyone <b>writes a line</b>: a scene, a saying, anything ("Suggest" helps).</li>
  <li>Your line goes to someone else, who <b>draws</b> it. Their drawing goes to someone else, who <b>describes</b> it. And so on, one step per player.</li>
  <li>You only ever see the one thing handed to you. A blank turn is filled in by the game.</li>
  <li>At the end the host shows each chain in the <b>album</b>, one entry at a time. No scores, just laughs.</li>
</ol>
<h4>Draw & guess</h4>
<ol>
  <li>Each round everyone takes a turn to <b>draw</b>: pick one of three words, then draw it while the others watch it appear.</li>
  <li>Everyone else <b>types guesses</b>. The word's letters show as boxes; a letter appears at half time and another at three quarters. One letter off tells you "Close!".</li>
  <li>A right guess earns <b>50 to 500</b>: the faster, the more. The drawer earns the average of what the guessers earned.</li>
  <li><b>Most points</b> after the last round wins; ties share the place.</li>
</ol>

