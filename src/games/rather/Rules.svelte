<p><b>Play</b> (one phone): read each <b>"Would you rather …"</b> aloud and have everyone pick with a show of hands. Argue about it. No scores.</p>
<p><b>Host</b> and <b>Join</b> (everyone on their own phone):</p>
<ol>
  <li>Everyone joins the host's room on their <b>own phone</b>. The host screen asks the question with two choices.</li>
  <li>Tap the choice you'd pick on your phone. Changed your mind? Tap the other one: your <b>last tap</b> counts. Nobody sees your pick until the reveal.</li>
  <li>When everyone has voted, or time is up, the screen shows <b>who picked what</b>. Argue about it.</li>
  <li>Everyone on the <b>bigger side</b> scores 1 point. A tie scores nobody.</li>
  <li>Most points after the last question wins.</li>
</ol>
