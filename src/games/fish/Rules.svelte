<ol>
  <li>Everyone joins the host's room on their <b>own phone</b>, which holds their cards. The host screen is the table. 2 or 3 players get 7 cards each; 4 to 6 get 5. The rest is the <b>pool</b>, face down.</li>
  <li>On your turn, tap a card in your hand to pick its rank, tap another player, then <b>Ask</b>. You can only ask for a rank you hold.</li>
  <li>If they have any, they must give you <b>all</b> of them, and you go again.</li>
  <li>If not: <b>Go fish!</b> You draw from the pool. Drew the rank you asked for? Show it and go again. Otherwise the turn passes on.</li>
  <li>Four of a rank is a <b>book</b>: it goes down at once. Run out of cards? Draw one on your turn.</li>
  <li>When all 13 books are down, the most books wins.</li>
