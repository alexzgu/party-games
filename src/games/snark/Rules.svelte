<ol>
  <li>One device is the <b>host screen</b>: a laptop on the TV, or a spare phone or tablet. Everyone joins on their own phone with the room code. Your phone also shows the answers, the votes and the scores, so nobody has to watch the host screen.</li>
  <li>Each round, your phone shows you <b>prompts</b>. Type the funniest answer you can think of, then tap Done.</li>
  <li>Every prompt goes to <b>two players</b>. Everyone sees both answers without names, and everyone else votes for the one they like best.</li>
  <li>Your points are your <b>share of the votes</b> (round 2 counts double), with a bonus for taking every vote.</li>
  <li>The <b>final round</b> is one prompt for everyone. Spread three votes over the answers you like (not your own). Every vote counts.</li>
  <li>Most points after the final wins. A phone that locks or reloads rejoins by itself and keeps its score.</li>
</ol>
