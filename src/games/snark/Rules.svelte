<ol>
  <li>One device is the <b>host screen</b> (a laptop on the TV, or a spare phone). Everyone joins on their <b>own phone</b> with the room code; your phone shows everything you need.</li>
  <li>Each round you get <b>prompts</b>. Type the funniest answer you can, then tap Done. Stuck? <b>Give me one</b> fills one in, at half points.</li>
  <li>Each prompt goes to <b>two players</b>. Everyone else sees both answers, without names, and <b>votes</b>.</li>
  <li>You score your <b>share of the votes</b>, plus a bonus for taking them all. Round 2 counts double.</li>
  <li>The <b>final</b> is one prompt for everyone: spread three votes over the answers you like (not your own). Or, if the host picked <b>three-line duels</b>, pairs each write three short lines and the room votes for the better set.</li>
  <li><b>Most points</b> wins. A phone that locks or reloads rejoins by itself.</li>
</ol>
